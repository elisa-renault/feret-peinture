<h3>Accès et protection</h3>

<p>Christophe Feret traite vos demandes. Aliant peut accéder ponctuellement aux données pour la maintenance. Le site est hébergé par netcup à Nuremberg, en Allemagne, et la messagerie par IONOS (Email Basic), avec un hébergement européen et sans accès hors de l’Espace économique européen (EEE) pour cette messagerie. Les demandes sont transmises par email, sans création de dossier client dans la base du site ; des copies peuvent subsister dans la messagerie et ses sauvegardes.</p>

<p>L’antispam utilise des identifiants dérivés de l’adresse IP et des preuves de vérification, sans enregistrer le message dans ses compteurs. ALTCHA fonctionne sur le site, sans service de captcha tiers. Des données de connexion peuvent figurer dans les journaux du serveur.</p>

